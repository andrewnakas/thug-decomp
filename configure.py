#!/usr/bin/env python3
"""Generate build.ninja and the link script from config/functions.us.csv.

    python configure.py && ninja          # build + sha1-verify SLUS_207.31

Each function is one object: src/funcs/<name>.cpp when it exists, otherwise the
splat asm. Every object's .text is pinned to the address it had in the original
executable, so a wrong-sized function cannot shift its neighbours: it fails the
sha1 (first_diff.py points at it) or the link ("cannot move location counter
backwards").

The file is rebuilt as: ELF header page (asm/bin/elfhdr.bin, from your disc)
+ the linked main LOAD segment + everything after it (asm/bin/elftail.bin:
the DNAS blob, non-alloc sections, section headers; also from your disc).
"""
import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tools"))
from common import (BUILD, CONFIG, EXE_NAME, EXE_SHA1, FILE_OFF, GP, SEG_END, VRAM,  # noqa: E402
                    load_functions, unit_path)

# Main-segment data objects (splat output) and the VU code blob, by vram.
DATA = [  # (vram, source, kind, sections)
    (0x347900, "asm/bin/vutext.bin", "bin", ".data"),
    (0x34D280, "asm/data/data.data.s", "as", ".data"),
    (0x35A900, "asm/data/rodata.rodata.s", "as", ".rodata"),
    (0x387400, "asm/data/lit4.rodata.s", "as", ".rodata"),
    (0x388280, "asm/data/sdata.data.s", "as", ".data"),
]
BSS = (0x393E80, "asm/data/bss.bss.s")
TOOL_DEPS = ["tools/cc.py", "tools/common.py", "toolchain/compiler.toml", "configure.py"]


def rel(p):
    return os.path.relpath(p, ROOT)


def obj_for(src):
    return BUILD / (rel(src) + ".o")


def link_script(text, data, bss_obj, cxx_aliases=()):
    def place(addr, o, sect):
        return f"        . = 0x{addr - VRAM:X}; {rel(o)}({sect})\n"

    out = ["/* generated by configure.py: do not edit */\n",
           "OUTPUT_ARCH(mips:5900)\n",
           "INCLUDE config/link_aliases.us.txt\n",
           "INCLUDE config/undefined_funcs_auto.us.txt\n",
           "INCLUDE config/undefined_syms_auto.us.txt\n",
           f"_gp = 0x{GP:08X};\n",
           # C++ units define mangled names; asm callers keep calling func_XXXXXXXX
           *[f"{name} = 0x{addr:08X};\n" for name, addr in cxx_aliases],
           "SECTIONS\n{\n",
           f"    .main 0x{VRAM:08X} : SUBALIGN(1)\n    {{\n"]
    for addr, o in text:
        out.append(place(addr, o, ".text"))
    for addr, o, sect in data:
        out.append(place(addr, o, sect))
    # .sdata ends on an odd byte (a string's NUL) that the disassembler leaves out: pin the end.
    out.append(f"        . = 0x{SEG_END - FILE_OFF:X};\n")
    out.append("    }\n")
    out.append(f"    .bss 0x{BSS[0]:08X} (NOLOAD) : SUBALIGN(1) {{ {rel(bss_obj)}(.bss .sbss) }}\n")
    out.append("    /DISCARD/ : { *(.reginfo) *(.MIPS.abiflags) *(.pdr) *(.comment) "
               "*(.gnu.attributes) *(.mdebug*) *(.gptab*) *(.note*) }\n}\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.parse_args()
    if not (CONFIG / "functions.us.csv").exists():
        sys.exit("config/functions.us.csv missing: run python tools/split.py")
    funcs = load_functions()
    objects = {}  # obj -> (rule, src)
    text = []
    aliases = []
    for f in funcs:
        c = unit_path(f["name"])
        src = c if c.exists() else ROOT / f["asm"]
        o = obj_for(src)
        objects[o] = ("cxx" if c.exists() else "as", src)
        text.append((f["addr"], o))
        if c.exists():
            aliases.append((f["name"], f["addr"]))
    data = []
    for addr, src, kind, sect in DATA:
        o = obj_for(ROOT / src)
        objects[o] = (kind, ROOT / src)
        data.append((addr, o, sect))
    bss_obj = obj_for(ROOT / BSS[1])
    objects[bss_obj] = ("as", ROOT / BSS[1])

    BUILD.mkdir(parents=True, exist_ok=True)
    ld = BUILD / "link.ld"
    ld.write_text(link_script(text, data, bss_obj, aliases))

    py = sys.executable
    deps = " ".join(TOOL_DEPS)
    n = ["# generated by configure.py: do not edit\nninja_required_version = 1.10\n",
         f"builddir = {rel(BUILD)}\n",
         f"rule cxx\n  command = {py} tools/cc.py cxx $in $out\n  description = cxx $in\n",
         f"rule as\n  command = {py} tools/cc.py asm $in $out\n  description = as $in\n",
         f"rule bin\n  command = {py} tools/cc.py bin $in $out\n  description = bin $in\n",
         f"rule ld\n  command = {py} tools/link.py $out\n  description = link $out\n",
         f"rule verify\n  command = {py} tools/link.py --verify $in $out\n  description = sha1 $in\n",
         f"rule configure\n  command = {py} configure.py\n  generator = 1\n  description = configure\n",
         "build build.ninja: configure | configure.py config/functions.us.csv\n"]
    headers = sorted(rel(p) for p in (ROOT / "include").rglob("*.h"))
    for o, (kind, src) in sorted(objects.items()):
        extra = " ".join(headers) if kind == "cxx" else ""
        n.append(f"build {rel(o)}: {kind} {rel(src)} | {deps} {extra}\n")
    exe = BUILD / EXE_NAME
    n.append(f"build {rel(exe)}: ld | {rel(ld)} tools/link.py asm/bin/elfhdr.bin asm/bin/elftail.bin "
             + " ".join(rel(o) for o in sorted(objects)) + "\n")
    n.append(f"build {rel(exe)}.ok: verify {rel(exe)}\n")

    # objdiff: one unit per game function (target = original asm, base = the C++)
    units = []
    for f in funcs:
        if f["source"] != "game" or f["kind"] != "func":
            continue
        c = unit_path(f["name"])
        u = {"name": f["name"], "target_path": rel(obj_for(ROOT / f["asm"]).with_name(
                 f["name"] + ".target.o")),
             "metadata": {"progress_categories": ["game"], "auto_generated": True}}
        if c.exists():
            t = Path(u["target_path"])
            n.append(f"build {t}: as {f['asm']} | {deps}\n")
            u["base_path"] = rel(obj_for(c))
            u["metadata"]["source_path"] = rel(c)
            u["metadata"]["complete"] = True
        units.append(u)
    (ROOT / "objdiff.json").write_text(json.dumps({
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "custom_make": "ninja", "build_target": False, "build_base": True,
        "watch_patterns": ["*.cpp", "*.c", "*.h"],
        "progress_categories": [{"id": "game", "name": "Game"}],
        "units": units}, indent=1) + "\n")
    n.append(f"default {rel(exe)}.ok\n")
    (ROOT / "build.ninja").write_text("".join(n))
    nc = sum(1 for k, _ in objects.values() if k == "cxx")
    print(f"configured: {len(text)} functions ({nc} in C++); expect sha1 {EXE_SHA1}")


if __name__ == "__main__":
    main()
