#!/usr/bin/env python3
"""Generate docs/REMAINING.md: every game function that is not an exact match, and why.

    python3 tools/remaining_report.py        # after tools/nonmatch.py --all --write

Inputs from the repo: config/functions.us.csv, src/{funcs,concession,nonmatching} (fuzzy lines, blocked: notes).
Optional maintainer-local inputs; a column shows "-" or "?" when one is absent:
  work/oracle_classes.tsv           oracle class per unit (tools/oracle_classify.py)
  build/concession/*.json           fewest differing words the directed force search reached (tools/concession.py)
  $THUG_GC_PAIRS                    GameCube pairing TSV (ps2_func, confidence), from the 2026-11-14 measurement
  work/closeout_b4_notes.txt        blocked notes that were not shipped in a unit file ("func_X|note" lines)
"""
import collections
import csv
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GC = Path(os.environ.get("THUG_GC_PAIRS", "/nonexistent"))

funcs = {r["name"]: r for r in csv.DictReader(open(ROOT / "config/functions.us.csv"))}
size = {n: int(r["size"], 16) for n, r in funcs.items()}
game = [n for n, r in funcs.items() if r["source"] == "game" and r["kind"] == "func"]
total = sum(size[n] for n in game)

matched = {p.stem for p in (ROOT / "src/funcs").glob("func_*.cpp")} & set(game)
conc = {p.stem for p in (ROOT / "src/concession").glob("func_*.cpp")} & set(game) - matched
nonm = {p.stem for p in (ROOT / "src/nonmatching").glob("func_*.cpp")} & set(game) - matched - conc
asm_only = set(game) - matched - conc - nonm

cls = {}
if (ROOT / "work/oracle_classes.tsv").exists():
    cls = {r["unit"]: r for r in csv.DictReader(open(ROOT / "work/oracle_classes.tsv"), delimiter="\t")}
best = {}
for f in (ROOT / "build/concession").glob("func_*.json"):
    d = json.loads(f.read_text())
    best[d["name"]] = d.get("best")
gc = {}
if GC.exists():
    for r in csv.DictReader(open(GC), delimiter="\t"):
        gc[r["ps2_func"]] = r["confidence"]
extra_notes = {}
p = ROOT / "work/closeout_b4_notes.txt"
if p.exists():
    for line in p.read_text().splitlines():
        n, _, note = line.partition("|")
        extra_notes[n] = note

FUZZY = re.compile(r"/\*\s*fuzzy:\s*([0-9.]+)\s*\*/")
BLOCK = re.compile(r"blocked:\s*(.*?)(?:\*/|$)", re.S)

# residue categories, checked in order on the unit's blocked note (and class / forced-search distance)
CATS = [
    ("asm", "Hand-written assembly", r"hand-written|no stack frame|handwritten"),
    ("case", "Switch case value not pinned by the binary", r"case value|switch tree|third case|4th case|case the binary"),
    ("dead", "Dead or unused value the game keeps", r"dead `|dead li|dead lb|never reads|result it never|unused|dead "),
    ("gcse", "gcse / PRE / cse / loop.c decision", r"gcse|\bpre\b|PRE|cse |cse\b|hoist|loop\.c|preheader|strength-reduc|fold"),
    ("reorg", "Delay-slot fill (reorg)", r"reorg|delay slot|delay-slot"),
    ("spill", "Stack/spill slot assignment", r"spill|stack slot|stack-slot|slot order"),
    ("ra", "Register choice or allocation order", r"register|\$[astv][0-9]|\$f[0-9]|allocno|find_reg|ga |global-alloc|swap"),
    ("sched", "Instruction scheduling order", r"sched|store order|load order|issue|luid|priority"),
]


def note_of(n, text):
    m = BLOCK.search(text)
    s = m.group(1) if m else extra_notes.get(n, "").replace("blocked:", "", 1)
    return " ".join(s.split())


def category(n, note):
    for key, _label, rx in CATS:
        if note and re.search(rx, note, re.I):
            return key
    c = cls.get(n, {}).get("cls")
    b = best.get(n)
    if b is not None and b <= 4:
        return "near"
    if c == "C":
        return "internal"
    return "shape"


LABEL = {k: l for k, l, _ in CATS}
LABEL.update(near="Within 4 words under forcing, no forced match",
             internal="Compiler-internal order the forces do not reach",
             shape="Code shape (instruction multisets differ), undiagnosed")

rows = []
for n in sorted(nonm):
    text = (ROOT / "src/nonmatching" / f"{n}.cpp").read_text(errors="replace")
    m = FUZZY.search(text)
    fz = float(m.group(1)) if m else 0.0
    note = note_of(n, text)
    rows.append(dict(n=n, size=size[n], fz=fz, cls=cls.get(n, {}).get("cls", "?"), best=best.get(n),
                     gc=gc.get(n, "-"), cat=category(n, note), note=note))


def pct(a):
    return 100.0 * a / total


b_m = sum(size[n] for n in matched)
b_c = sum(size[n] for n in conc)
b_n = sum(size[n] for n in nonm)
b_a = sum(size[n] for n in asm_only)
fuzzy_bytes = b_m + b_c * 0.999 + sum(r["size"] * min(r["fz"], 99.9) / 100 for r in rows)

out = []
w = out.append
w("# What is left, and why")
w("")
w("This page accounts for every game function that is not yet an exact, concession-free match. It is generated by")
w("`tools/remaining_report.py` from the repo itself, the oracle classification (`work/oracle_classes.tsv`), the")
w("directed force-search results and the GameCube pairing (see below). Numbers are code bytes of game functions")
w("(Sony SDK, OpenSSL, GameSpy and libgcc are excluded, as in the progress report).")
w("")
w("## Totals")
w("")
w("| Tier | Functions | Bytes | Share of game code |")
w("|---|---|---|---|")
w(f"| Exact match, plain C++ (`src/funcs/`) | {len(matched):,} | {b_m:,} | {pct(b_m):.2f}% |")
w(f"| Exact under recorded compiler decisions (`src/concession/`) | {len(conc):,} | {b_c:,} | {pct(b_c):.2f}% |")
w(f"| Equivalent C++, not byte-exact (`src/nonmatching/`) | {len(nonm):,} | {b_n:,} | {pct(b_n):.2f}% |")
w(f"| Left as assembly (docs/ASM_ONLY.md) | {len(asm_only):,} | {b_a:,} | {pct(b_a):.2f}% |")
w(f"| **Total** | **{len(game):,}** | **{total:,}** | |")
w("")
w(f"- **Exact (headline):** {pct(b_m):.2f}%.")
w(f"- **Exact including concessions:** {pct(b_m + b_c):.2f}%.")
w(f"- **Fuzzy** (each non-matching unit weighted by its similarity score): {pct(fuzzy_bytes):.2f}%.")
w("")
w("Every non-matching and concession unit is compiled and run by the functional build")
w("(`tools/build_functional.py`), which boots and plays into the first level in PCSX2 with frames matching the")
w("original (`tools/pcsx2_boot.py ... --route level`; boot the original and the functional build back to back")
w("under the same machine load and compare). So all of this C++ is behaviourally verified, not only scored.")
w("")
w("## Why the remaining functions do not match")
w("")
w("Every non-matching unit has already been through: the first and second class-B structural sweeps, the oracle")
w("classification, and the directed force search with every accepted force kind (`ga`, `la`, `sched` incl.")
w("replay and two-slot picks, `spill`, `fr`, `lfr`, `reorg`, `cprop`). Most also had a lane rewrite pass with")
w("at most 3 strategies. What is left falls into these residues (from each unit's `blocked:` note where it has")
w("one, else from its oracle class and how close the forced search got):")
w("")
w("| Residue | Units | Bytes | What it means |")
w("|---|---|---|---|")
MEAN = {
    "shape": "The game's instruction multiset differs from ours: a source shape nobody has found yet (often a cse/gcse/loop.c consequence of how the original was written).",
    "internal": "Only the order of a compiler-internal decision differs, of a kind the oracle can see but no force kind reaches (PRE reaching-register order, dependents counts, reg-weight keys).",
    "near": "Forcing gets within 4 differing words but never to 0: usually two interacting decisions, one of them outside the force kinds.",
    "gcse": "A cse, gcse/PRE or loop.c decision (a hoist, a fold, a copy-propagation) differs. Declining a cprop or PRE was tried; reversing one would bypass legality checks, so it is not offered.",
    "ra": "Register choice or allocation order, in a form `fr`/`lfr`/`ga` cannot express (reload's choice, a preference inherited from another pseudo, float registers in a helper used twice).",
    "sched": "Instruction order: ready-list keys set by sched1 (priority, reg weight, dependents) that a sched2 pick cannot change, or load/store order fixed by dependences.",
    "spill": "Stack slot assignment that the `spill` order force cannot produce (a slot reused vs a fresh one).",
    "reorg": "A delay slot filled from the other thread in a way the `reorg` prediction force does not reach.",
    "dead": "The game keeps a value or test whose result is never used; reproducing it would need dead code, which the rules forbid (instruction test, MATCHING_GUIDE.md).",
    "case": "A switch's compare tree implies a case value the binary does not pin uniquely; inventing one is forbidden (case-value ruling).",
    "asm": "The game's code is hand-written assembly (no compiler frame): C++ cannot produce it.",
}
byc = collections.defaultdict(list)
for r in rows:
    byc[r["cat"]].append(r)
for k in sorted(byc, key=lambda k: -sum(r["size"] for r in byc[k])):
    v = byc[k]
    w(f"| {LABEL[k]} | {len(v)} | {sum(r['size'] for r in v):,} | {MEAN[k]} |")
w("")
w("## What was tried that did not help (do not repeat)")
w("")
w("- **Other compiler builds** (SN 2.95.3-114/-107, 2.95.2-274/-273a): none matched; every apparent gain was an")
w("  alignment artefact (LAST_MILE.md, \"per-function compiler build\").")
w("- **Unlisted flags** (`-fforce-addr`, `-fno-cse-follow-jumps`, ...): diagnostics only; the allowed per-file")
w("  flags need neighbour evidence (MATCHING_GUIDE.md).")
w("- **Declaration-context padding**: 0 of 1,296 compiles changed a word (LAST_MILE.md 1.3).")
w("- **The GameCube retail build as a shape reference** (2026-11-14): it pairs with 183 of these units (150 at high")
w("  confidence, 99.7% precision measured on matched functions), and its call skeletons agree with ours almost")
w("  exactly (func_0022F500: 111 of 111 calls in order). In a 10-unit sample of the largest units it revealed no")
w("  structural error in our drafts; the residue is allocation and scheduling, which a different compiler cannot")
w("  inform. Other platform builds (Xbox) are expected to behave the same. A prototype build was not used: internal")
w("  builds are excluded by PROVENANCE.md.")
w("- **Wider force searches**: a beam of 3 with 200 compiles on the units left at 1-4 words found nothing more; a")
w("  `pre` decline kind exists in the oracle as a diagnostic only (no identity check is possible yet).")
w("")
w("## Every non-matching unit")
w("")
w("Columns: size in bytes; fuzzy score; oracle class (B = instruction multisets differ, C = internal order, A = a")
w("source-reachable tie); the fewest differing words any directed force search reached (`-` = no candidate); the")
w("GameCube pairing confidence; the residue; and the unit's own `blocked:` note, shortened.")
w("")
w("| Unit | Size | Fuzzy | Class | Forced best | GC | Residue | Note |")
w("|---|---|---|---|---|---|---|---|")
for r in sorted(rows, key=lambda r: -r["size"] * (100 - r["fz"])):
    note = r["note"].replace("|", "/")
    if len(note) > 150:
        note = note[:147] + "..."
    b = "-" if r["best"] is None else str(r["best"])
    w(f"| {r['n']} | {r['size']} | {r['fz']:.1f} | {r['cls']} | {b} | {r['gc']} | {LABEL[r['cat']]} | {note} |")
w("")
w("Rows are ordered by gap (size × (100 − fuzzy)), largest first: the top of the table is where the remaining bytes")
w("are.")
w("")
(ROOT / "docs/REMAINING.md").write_text("\n".join(out))
print(f"exact {pct(b_m):.3f}%  with concessions {pct(b_m + b_c):.3f}%  fuzzy {pct(fuzzy_bytes):.3f}%  "
      f"nonmatching {len(nonm)}  concession {len(conc)}  asm-only {len(asm_only)}")
print({LABEL[k]: len(v) for k, v in byc.items()})
